    fun getStatistics(): DirectoryStatistics {
        val total = items.size
        val functional = items.count { it.functionalStatus == FunctionalStatus.FUNCTIONAL }
        val partial = items.count { it.functionalStatus == FunctionalStatus.PARTIAL }
        val notImplemented = items.count { it.functionalStatus == FunctionalStatus.NOT_IMPLEMENTED }
        val visible = items.count { it.visibleInUi }
        val hidden = items.count { !it.visibleInUi }
        val requiresPerm = items.count { it.requiredPermissions.isNotEmpty() }
        val androidNative = items.count { it.implementationType == ImplementationType.ANDROID_NATIVE }
        val uiOnly = items.count { it.implementationType == ImplementationType.UI_ONLY }
        val backendService = items.count { it.implementationType == ImplementationType.BACKEND_SERVICE }

        return DirectoryStatistics(
            totalCount = total,
            functionalCount = functional,
            partialCount = partial,
            notImplementedCount = notImplemented,
            visibleCount = visible,
            hiddenCount = hidden,
            requiresPermissionCount = requiresPerm,
            androidNativeCount = androidNative,
            uiOnlyCount = uiOnly,
            backendServiceCount = backendService
        )
    }
